-- Applied by Flyway to PostgreSQL only

CREATE TABLE documents (
    document_id  uuid PRIMARY KEY,
    doc_title    text,              -- NULL = never resolved (repository read failed)
    record_type  text,
    removed_at   timestamptz        -- set when the catalogue no longer has the record; row is kept
);

CREATE INDEX idx_documents_record_type ON documents (record_type);

CREATE TABLE metric_counts (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id    uuid        NOT NULL REFERENCES documents (document_id),
    metric_type    text        NOT NULL CHECK (metric_type IN ('view', 'download')),
    counted_from   timestamptz NOT NULL,
    counted_until  timestamptz NOT NULL,
    amount         integer     NOT NULL
);
COMMENT ON COLUMN metric_counts.counted_from  IS 'Start of the period amount was counted over (inclusive)';
COMMENT ON COLUMN metric_counts.counted_until IS 'End of the period amount was counted over (exclusive)';

CREATE INDEX idx_metric_counts_document_type
    ON metric_counts (document_id, metric_type)
    INCLUDE (amount);

CREATE INDEX idx_metric_counts_counted_from
    ON metric_counts (counted_from)
    INCLUDE (counted_until, document_id, metric_type, amount);
